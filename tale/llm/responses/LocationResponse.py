from tale import load_items, parse_utils
from tale.base import Location
from tale.llm.schemas import LocationSchema


class LocationResponse():

    def __init__(self, model: LocationSchema,
                    location: Location,
                    exit_location_name: str,
                    world_items: dict = {},
                    world_creatures: dict = {},
                    neighbors: dict = {},
                    item_types: dict = {}):


        self.new_locations = []
        self.exits = []
        self.npcs = []
        self.items = []
        self.item_types = item_types
        if not model:
            self.valid = False
            return
        if model.name:
            location.name = model.name

        self.valid = self._validate_location(model,
                                            location,
                                            exit_location_name=exit_location_name,
                                            world_items=world_items,
                                            world_creatures=world_creatures,
                                            neighbors=neighbors)

    def _validate_location(self, model: LocationSchema,
                           location_to_build: Location,
                           exit_location_name: str,
                           world_items: dict = {},
                           world_creatures: dict = {},
                           neighbors: dict = {}):
        """Validate the location generated by LLM and update the location object."""
        try:
            if not location_to_build.description:
                description = model.description
                if not description:
                    description = exit_location_name
                location_to_build.description = description

            if model.indoors:
                location_to_build.indoors = True

            self.items = self._add_items(location_to_build, model, world_items)

            self.npcs = self._add_npcs(location_to_build, model, world_creatures, world_items).values()

            exits_data = [e.model_dump() for e in model.exits]
            new_locations, exits = parse_utils.parse_generated_exits(exits_data,
                                                                     exit_location_name,
                                                                     location_to_build)
            location_to_build.built = True
            self.new_locations = new_locations
            self.exits = exits
            return True
        except Exception as exc:
            print(f'Exception while parsing location {model} ')
            return False


    def _add_items(self, location: Location, model: LocationSchema, world_items: dict = {}):
        generated_items = [i.model_dump() for i in model.items]
        if not generated_items:
            return []

        if world_items:
            generated_items = parse_utils.replace_items_with_world_items(generated_items, world_items)
        items = self._validate_items(generated_items)
        items = load_items.load_items(items)
        for item in items.values():
            location.insert(item, None)
        return [items]

    def _add_npcs(self, location: Location, model: LocationSchema, world_creatures: dict = {}, world_items: dict = {}) -> dict:
        generated_npcs = [n.model_dump() for n in model.npcs]
        if not generated_npcs:
            return {}
        if world_creatures:
            generated_npcs = parse_utils.replace_creature_with_world_creature(generated_npcs, world_creatures)
        try:
            generated_npcs = parse_utils.load_npcs(generated_npcs, world_items=world_items, parse_occupation=True)
            for npc in generated_npcs.values():
                location.insert(npc, None)
        except Exception as exc:
            print(exc)
        return generated_npcs


    def _validate_items(self, items: list) -> list:
        new_items = []
        for item in items:
            if isinstance(item, str):
                new_items.append({"name": item, "type": "Other"})
                continue
            if not item.get("name", ""):
                continue
            item["name"] = item["name"].lower()
            item_type = item.get("type", "Other")
            if item_type not in self.item_types:
                item["type"] = "Other"
            new_items.append(item)
        return new_items

    @classmethod
    def empty(cls):
        return cls(model=None, location=None, exit_location_name='')
